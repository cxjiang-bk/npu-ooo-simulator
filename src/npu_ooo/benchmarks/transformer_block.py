from __future__ import annotations

from npu_ooo.ir import (
    BenchmarkCase,
    DataEdge,
    EvaluationScope,
    ExecutionPhase,
    GraphTemplate,
    ModelFamily,
    ModelSpec,
    OperatorGraph,
    OperatorSpec,
    SemanticOpType,
    TensorSpec,
)


def build_transformer_block_model(
    *,
    tokens: int = 64,
    sequence: int = 64,
    head_dim: int = 32,
    intermediate: int = 64,
) -> ModelSpec:
    """Build a decoder-block-shaped graph with explicit attention and MLP stages."""

    graph = OperatorGraph(
        graph_id="transformer_block_micro_graph",
        tensors=(
            TensorSpec("X", ("M", "D")),
            TensorSpec("Norm", ("M", "D")),
            TensorSpec("K_T", ("D", "S"), attributes={"transposed": True}),
            TensorSpec("Scores", ("M", "S"), attributes={"intermediate": True}),
            TensorSpec("P", ("M", "S"), attributes={"intermediate": True}),
            TensorSpec("V", ("S", "D")),
            TensorSpec("Context", ("M", "D"), attributes={"intermediate": True}),
            TensorSpec("AttnOut", ("M", "D"), attributes={"intermediate": True}),
            TensorSpec("W1", ("D", "H")),
            TensorSpec("Hidden", ("M", "H"), attributes={"intermediate": True}),
            TensorSpec("HiddenAct", ("M", "H"), attributes={"intermediate": True}),
            TensorSpec("W2", ("H", "D")),
            TensorSpec("MlpOut", ("M", "D"), attributes={"intermediate": True}),
            TensorSpec("Y", ("M", "D")),
        ),
        operators=(
            OperatorSpec(
                op_id="block_norm",
                op_type=SemanticOpType.LAYERNORM,
                inputs=("X",),
                outputs=("Norm",),
                iteration_dims=(("M", "M"),),
                reduction_dims=(("D", "D"),),
                attributes={"axis": "D", "epsilon": 1e-5},
                provenance={"block_stage": "pre_attention_norm"},
            ),
            OperatorSpec(
                op_id="block_scores",
                op_type=SemanticOpType.MATMUL,
                inputs=("Norm", "K_T"),
                outputs=("Scores",),
                iteration_dims=(("M", "M"), ("S", "S")),
                reduction_dims=(("D", "D"),),
                attributes={"scale": "1/sqrt(D)"},
                provenance={"block_stage": "qk_scores"},
            ),
            OperatorSpec(
                op_id="block_softmax",
                op_type=SemanticOpType.SOFTMAX,
                inputs=("Scores",),
                outputs=("P",),
                iteration_dims=(("M", "M"),),
                reduction_dims=(("S", "S"),),
                attributes={"axis": "S", "causal": False},
                provenance={"block_stage": "attention_softmax"},
            ),
            OperatorSpec(
                op_id="block_context",
                op_type=SemanticOpType.MATMUL,
                inputs=("P", "V"),
                outputs=("Context",),
                iteration_dims=(("M", "M"), ("D", "D")),
                reduction_dims=(("S", "S"),),
                provenance={"block_stage": "pv_context"},
            ),
            OperatorSpec(
                op_id="block_attn_residual",
                op_type=SemanticOpType.RESIDUAL_ADD,
                inputs=("Context", "X"),
                outputs=("AttnOut",),
                iteration_dims=(("M", "M"), ("D", "D")),
                provenance={"block_stage": "attention_residual"},
            ),
            OperatorSpec(
                op_id="block_mlp1",
                op_type=SemanticOpType.MATMUL,
                inputs=("AttnOut", "W1"),
                outputs=("Hidden",),
                iteration_dims=(("M", "M"), ("H", "H")),
                reduction_dims=(("D", "D"),),
                provenance={"block_stage": "mlp_up"},
            ),
            OperatorSpec(
                op_id="block_activation",
                op_type=SemanticOpType.ELEMENTWISE,
                inputs=("Hidden",),
                outputs=("HiddenAct",),
                iteration_dims=(("M", "M"), ("H", "H")),
                provenance={"block_stage": "mlp_activation", "activation": "gelu"},
            ),
            OperatorSpec(
                op_id="block_mlp2",
                op_type=SemanticOpType.MATMUL,
                inputs=("HiddenAct", "W2"),
                outputs=("MlpOut",),
                iteration_dims=(("M", "M"), ("D", "D")),
                reduction_dims=(("H", "H"),),
                provenance={"block_stage": "mlp_down"},
            ),
            OperatorSpec(
                op_id="block_mlp_residual",
                op_type=SemanticOpType.RESIDUAL_ADD,
                inputs=("MlpOut", "AttnOut"),
                outputs=("Y",),
                iteration_dims=(("M", "M"), ("D", "D")),
                provenance={"block_stage": "mlp_residual"},
            ),
        ),
        edges=(
            DataEdge("block_norm", "block_scores", "Norm"),
            DataEdge("block_scores", "block_softmax", "Scores"),
            DataEdge("block_softmax", "block_context", "P"),
            DataEdge("block_context", "block_attn_residual", "Context"),
            DataEdge("block_attn_residual", "block_mlp1", "AttnOut"),
            DataEdge("block_mlp1", "block_activation", "Hidden"),
            DataEdge("block_activation", "block_mlp2", "HiddenAct"),
            DataEdge("block_mlp2", "block_mlp_residual", "MlpOut"),
        ),
        attributes={
            "pattern": "pre_norm_attention_mlp",
            "single_head": True,
            "causal_mask": False,
            "kv_cache": False,
        },
    )
    return ModelSpec(
        model_id="transformer_block_micro",
        family=ModelFamily.DECODER_TRANSFORMER,
        variant="pre-norm-attention-mlp-v0",
        shape_symbols=(
            ("M", tokens),
            ("S", sequence),
            ("D", head_dim),
            ("H", intermediate),
        ),
        templates=(GraphTemplate("transformer_block_micro", graph, parameters=("M", "S", "D", "H")),),
        top_level_template="transformer_block_micro",
        dtype_policy="fp16",
        attributes={"scope_note": "shape-only decoder block skeleton"},
    )


def build_transformer_block_case(
    *,
    tokens: int = 64,
    architecture_profile: str = "minimal",
    scheduler_profile: str = "sequential",
) -> BenchmarkCase:
    return BenchmarkCase(
        case_id="transformer_block_micro_default",
        model_id="transformer_block_micro",
        evaluation_scope=EvaluationScope.ONE_BLOCK,
        phase=ExecutionPhase.PREFILL,
        batch=1,
        sequence_length=tokens,
        dtype="fp16",
        architecture_profile=architecture_profile,
        scheduler_profile=scheduler_profile,
        attributes={"scope_note": "LayerNorm + QK-softmax-PV + MLP + residuals"},
    )
